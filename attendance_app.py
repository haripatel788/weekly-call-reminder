"""
Attendance logger web UI for the weekly call.

A small Flask app that:
  1. Renders a checkbox list of the Roster.
  2. On submit, increments each checked person's count in a new
     "Attendance Tracker" tab (auto-created on first use), and fills the
     existing "Total Attendance" + "No Shows" columns on the most recent
     Tracker row.
  3. Optionally posts a confirmation to the Telegram thread. If a Groq
     API key is configured, the confirmation message is generated by
     Llama 3.3 70B for a warmer, personalised tone; otherwise a clean
     templated string is used.

Designed to deploy as a Cloud Run *Service* on the same Docker image as
bot.py. Cloud Run runs `gunicorn attendance_app:app` instead of
`python bot.py`; everything else (image, secrets, service account) is
shared with the existing weekly-call Job.
"""

