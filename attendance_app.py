def _col_letter(n: int) -> str:
    """1-based column index -> spreadsheet letters (1 -> A, 27 -> AA)."""
    s = ""
    while n:
        n, r = divmod(n - 1, 26)
        s = chr(65 + r) + s
    return s


def connect_to_sheet():
    if not GCP_CREDENTIALS_JSON:
        raise RuntimeError("GCP_CREDENTIALS env var is not set")
    scope = [
        "https://www.googleapis.com/auth/spreadsheets",
        "https://www.googleapis.com/auth/drive",
    ]
    creds = Credentials.from_service_account_info(
        json.loads(GCP_CREDENTIALS_JSON), scopes=scope
    )
    return gspread.authorize(creds).open(SHEET_NAME)


def read_roster(spreadsheet):
    ws = spreadsheet.worksheet(ROSTER_TAB)
    rows = ws.get_all_values()
    if len(rows) <= 1:
        return []
    out = []
    for row in rows[1:]:
        if not row or not row[0].strip():
            continue
        name = row[0].strip()
        tag = row[1].strip() if len(row) > 1 else ""
        status = row[2].strip().lower() if len(row) > 2 else ""
        out.append(
            {
                "name": name,
                "tag": tag or name,
                "on_vacation": status == "vacation",
            }
        )
    return out


def find_current_call_row(tracker_ws):
    """
    Locate the Tracker row for the most recently completed call.

    The bot writes a row each Monday with `Date of Call` set to the
    upcoming Tuesday. After that Tuesday's call we look up the row by
    that Tuesday's date. If the exact date isn't found (timing edge
    case), fall back to the last row in the sheet.
    """
    records = tracker_ws.get_all_records()
    if not records:
        return None, None
    now = datetime.now(TZ)
    days_since_tuesday = (now.weekday() - 1) % 7
    target_date = (now - timedelta(days=days_since_tuesday)).date()
    target_str = target_date.strftime("%b %d, %Y")
    for i, row in enumerate(records, start=2):
        if str(row.get(COL_WEEK_OF, "")).strip() == target_str:
            return i, row
    return len(records) + 1, records[-1]


def get_or_create_attendance_tab(spreadsheet):
    try:
        return spreadsheet.worksheet(ATTENDANCE_TAB)
    except gspread.WorksheetNotFound:
        ws = spreadsheet.add_worksheet(title=ATTENDANCE_TAB, rows=200, cols=4)
        ws.append_row(["Name", "Attended Count", "Last Attended"])
        return ws


def update_attendance_tab(spreadsheet, attended_names, call_date_str):
    ws = get_or_create_attendance_tab(spreadsheet)
    values = ws.get_all_values()
    name_to_row = {}
    for i, row in enumerate(values[1:], start=2):
        if row and row[0].strip():
            name_to_row[row[0].strip()] = (i, row)

    batch_updates = []
    new_rows = []
    for name in attended_names:
        if name in name_to_row:
            row_idx, row_vals = name_to_row[name]
            try:
                current = int(row_vals[1]) if len(row_vals) > 1 and row_vals[1] else 0
            except ValueError:
                current = 0
            batch_updates.append(
                {
                    "range": f"B{row_idx}:C{row_idx}",
                    "values": [[current + 1, call_date_str]],
                }
            )
        else:
            new_rows.append([name, 1, call_date_str])

    if batch_updates:
        ws.batch_update(batch_updates)
    if new_rows:
        ws.append_rows(new_rows)


def update_tracker_row(tracker_ws, row_idx, headers, attended_count, no_shows_str):
    try:
        total_col = headers.index(COL_TOTAL_ATTENDANCE) + 1
        no_show_col = headers.index(COL_NO_SHOWS) + 1
    except ValueError as e:
        raise RuntimeError(f"Missing column in Tracker tab: {e}")
    tracker_ws.batch_update(
        [
            {"range": f"{_col_letter(total_col)}{row_idx}", "values": [[attended_count]]},
            {"range": f"{_col_letter(no_show_col)}{row_idx}", "values": [[no_shows_str]]},
        ]
    )


def generate_telegram_summary(call_date, attended, no_shows, role_holders_map):
    """Return the Telegram confirmation text. Uses Groq when configured."""
    if HAS_GROQ and GROQ_API_KEY:
        try:
            client = Groq(api_key=GROQ_API_KEY)
            roles_text = ", ".join(
                f"{role}={name}" for role, name in role_holders_map.items() if name
            )
            prompt = (
                "Write a short Telegram confirmation message (3-5 lines max) "
                "recapping a BAPS Swaminarayan weekly preparation call's "
                "attendance. Warm and uplifting but factual. Use names "
                "directly. Plain text only, no markdown, simple newlines.\n\n"
                f"Call date: {call_date}\n"
                f"Attended ({len(attended)}): {', '.join(attended)}\n"
                f"Role-holders this week: {roles_text}\n"
                f"No-shows from role-holders ({len(no_shows)}): "
                f"{', '.join(no_shows) if no_shows else 'None - all role-holders attended'}\n\n"
                'End with "Jai Swaminarayan!"'
            )
            resp = client.chat.completions.create(
                model="llama-3.3-70b-versatile",
                messages=[{"role": "user", "content": prompt}],
                temperature=0.6,
                max_tokens=220,
            )
            return resp.choices[0].message.content.strip()
        except Exception as e:
            print(f"Groq summary failed, using template: {e}", flush=True)

    lines = [f"Attendance logged for {call_date}", ""]
    lines.append(f"{len(attended)} attended: {', '.join(attended)}")
    if no_shows:
        plural = "s" if len(no_shows) != 1 else ""
        lines.append(
            f"{len(no_shows)} no-show{plural} from role-holders: {', '.join(no_shows)}"
        )
    else:
        lines.append("All role-holders attended.")
    return "\n".join(lines)


def post_to_telegram(text):
    if not (BOT_TOKEN and CHAT_ID):
        return
    payload = {"chat_id": int(CHAT_ID), "text": text}
    if THREAD_ID:
        payload["message_thread_id"] = int(THREAD_ID)
    try:
        requests.post(
            f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage",
            json=payload,
            timeout=20,
        )
    except Exception as e:
        print(f"Telegram post failed (non-fatal): {e}", flush=True)


