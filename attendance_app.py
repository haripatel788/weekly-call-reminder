@app.route("/", methods=["GET"])
def index():
    try:
        spreadsheet = connect_to_sheet()
        roster = read_roster(spreadsheet)
        tracker = spreadsheet.worksheet(TRACKER_TAB)
        _, current_row = find_current_call_row(tracker)
    except Exception as e:
        return f"<pre>Error loading sheet:\n{e}</pre>", 500

    call_date = current_row.get(COL_WEEK_OF, "?") if current_row else "?"
    role_holders = {}
    if current_row:
        role_holders = {
            "Shlok + Jaynaad": current_row.get(COL_SHLOK, ""),
            "Prasang": current_row.get(COL_PRASANG, ""),
            "Ending Shlok": current_row.get(COL_ENDING_SHLOK, ""),
            "Announcements": HARIBHAI_NAME,
        }

    return render_template_string(
        INDEX_HTML,
        roster=roster,
        role_holders=role_holders,
        call_date=call_date,
    )


@app.route("/submit", methods=["POST"])
def submit():
    passcode = request.form.get("passcode", "")
    if not ATTENDANCE_PASSCODE or passcode != ATTENDANCE_PASSCODE:
        return "<pre>Incorrect passcode.</pre>", 401

    attended = request.form.getlist("attended")
    if not attended:
        return "<pre>No attendees selected.</pre>", 400

    try:
        spreadsheet = connect_to_sheet()
        tracker = spreadsheet.worksheet(TRACKER_TAB)
        row_idx, current_row = find_current_call_row(tracker)
        if not row_idx or not current_row:
            return "<pre>Could not find current week's row in Tracker.</pre>", 404

        headers = tracker.row_values(1)
        call_date = current_row.get(COL_WEEK_OF, "")

        role_holders_map = {
            "Shlok + Jaynaad": current_row.get(COL_SHLOK, ""),
            "Prasang": current_row.get(COL_PRASANG, ""),
            "Ending Shlok": current_row.get(COL_ENDING_SHLOK, ""),
            "Announcements": HARIBHAI_NAME,
        }
        role_holders = [v for v in role_holders_map.values() if v]
        attended_set = set(attended)
        no_shows = [r for r in role_holders if r not in attended_set]
        no_shows_str = ", ".join(no_shows) if no_shows else "None"

        update_tracker_row(tracker, row_idx, headers, len(attended), no_shows_str)
        update_attendance_tab(spreadsheet, attended, call_date)

        if POST_TELEGRAM_CONFIRMATION:
            summary = generate_telegram_summary(
                call_date, attended, no_shows, role_holders_map
            )
            post_to_telegram(summary)

        return render_template_string(
            SUCCESS_HTML,
            attended=attended,
            no_shows=no_shows,
            call_date=call_date,
        )
    except Exception as e:
        return f"<pre>Error:\n{e}\n\n{traceback.format_exc()}</pre>", 500


